#!/usr/bin/env python3
"""The Vulkan backend's shaders: runtime/shaders/*.vert and *.frag are compiled to SPIR-V and the result is checked in as
runtime/gfx_vk_spv.c and gfx_vk_spv.h (C arrays), so nobody needs a shader compiler to build the game.

  python tools/shaders.py check                       needs no compiler: fails when a source changed without the SPIR-V being regenerated
  python tools/shaders.py build path/to/glslang       compiles every shader, rewrites gfx_vk_spv.c, gfx_vk_spv.h and shaders/hashes.txt

Different compiler versions give different bytes for the same source, so nothing compares bytes. hashes.txt holds, per shader,
the SHA-256 of the source (line endings normalised) plus the compiler options; `check` recomputes those. It cannot tell whether the
SPIR-V in gfx_vk_spv.c is the right output for the source, only that the source has not changed since it was made."""
import hashlib, os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, 'runtime', 'shaders')
SPV_C = os.path.join(ROOT, 'runtime', 'gfx_vk_spv.c')
SPV_H = os.path.join(ROOT, 'runtime', 'gfx_vk_spv.h')
HASHES = os.path.join(SHADERS, 'hashes.txt')
OPTIONS = '-V --target-env vulkan1.0'      # SPIR-V 1.0: the backend asks Vulkan 1.0 for the instance

def sources():
    return sorted(f for f in os.listdir(SHADERS) if f.endswith(('.vert', '.frag')))

def digest(name):
    text = open(os.path.join(SHADERS, name), 'rb').read().replace(b'\r\n', b'\n')
    return hashlib.sha256(text + b'\0' + OPTIONS.encode()).hexdigest()

def ident(name):
    return name.replace('.', '_')

def check():
    want = {}
    if os.path.exists(HASHES):
        for line in open(HASHES, encoding='utf-8'):
            if line.strip() and not line.startswith('#'):
                h, n = line.split()
                want[n] = h
    bad = [n for n in sources() if want.get(n) != digest(n)]
    bad += [n for n in want if n not in sources()]
    if bad:
        print('stale or missing in shaders/hashes.txt: ' + ', '.join(bad))
        print('regenerate with: python tools/shaders.py build <glslang>')
        return 1
    print('shaders: %d sources, hashes match' % len(want))
    return 0

def build(tool):
    note = '/* Generated by tools/shaders.py build: SPIR-V for the files in runtime/shaders. Do not edit by hand. */'
    out = [note, '#include "gfx_vk_spv.h"', '']
    hdr = [note, '#ifndef GFX_VK_SPV_H', '#define GFX_VK_SPV_H', '#include <stdint.h>', '']
    lines = ['# sha256 of source + compiler options (' + OPTIONS + '), checked by tools/shaders.py check']
    for n in sources():
        spv = os.path.join(tempfile.mkdtemp(), n + '.spv')
        r = subprocess.run([tool] + OPTIONS.split() + ['-o', spv, os.path.join(SHADERS, n)], capture_output=True, text=True)
        if r.returncode:
            print(r.stdout + r.stderr); return 1
        data = open(spv, 'rb').read()
        assert len(data) % 4 == 0
        words = struct.unpack('<%dI' % (len(data) // 4), data)
        out.append('const uint32_t spv_%s[%d] = {' % (ident(n), len(words)))
        hdr.append('extern const uint32_t spv_%s[%d];' % (ident(n), len(words)))
        for i in range(0, len(words), 8):
            out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
        out += ['};', '']
        lines.append('%s  %s' % (digest(n), n))
    hdr += ['#endif', '']
    open(SPV_C, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    open(SPV_H, 'w', encoding='utf-8', newline='\n').write('\n'.join(hdr))
    open(HASHES, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', SPV_C, SPV_H, 'and', HASHES)
    return 0

if __name__ == '__main__':
    if len(sys.argv) == 2 and sys.argv[1] == 'check': sys.exit(check())
    if len(sys.argv) == 3 and sys.argv[1] == 'build': sys.exit(build(sys.argv[2]))
    print(__doc__); sys.exit(2)
